void XvtSnapshot_EncodeMobileObject(XvtSnapshotMobileObject* record, const MobileObject* live) {
	XvtSnapshot_CopyFields((void*)record, (void*)live, g_MobileObjectFields,
						   sizeof(g_MobileObjectFields) / sizeof(g_MobileObjectFields[0]), 0);
	record->pWarheadGuidance = live->pWarheadGuidance
								   ? (uint32_t)((live->pWarheadGuidance - g_projectileGuidanceStates) *
													sizeof(WarheadGuidanceState) +
												1)
								   : 0;
	record->pCraft = live->pCraft
						 ? (uint32_t)((live->pCraft - g_craftDataPoolBase) * sizeof(XvtSnapshotCraftData) + 1)
						 : 0;
	record->pCharData = live->pCharData ? (uint32_t)((live->pCharData - g_mobileObjectCharDataPool) *
														 sizeof(XvtSnapshotMobileObjectCharData) +
													 1)
										: 0;
}

void XvtSnapshot_DecodeMobileObject(MobileObject* live, const XvtSnapshotMobileObject* record) {
	XvtSnapshot_CopyFields((void*)record, (void*)live, g_MobileObjectFields,
						   sizeof(g_MobileObjectFields) / sizeof(g_MobileObjectFields[0]), 1);
	live->pWarheadGuidance =
		record->pWarheadGuidance
			? &g_projectileGuidanceStates[(record->pWarheadGuidance - 1) / sizeof(WarheadGuidanceState)]
			: NULL;
	live->pCraft =
		record->pCraft ? &g_craftDataPoolBase[(record->pCraft - 1) / sizeof(XvtSnapshotCraftData)] : NULL;
	live->pCharData =
		record->pCharData
			? &g_mobileObjectCharDataPool[(record->pCharData - 1) / sizeof(XvtSnapshotMobileObjectCharData)]
			: NULL;
}

