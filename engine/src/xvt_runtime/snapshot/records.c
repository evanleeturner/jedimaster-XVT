void XvtSnapshot_EncodeCraftData(XvtSnapshotCraftData* record, const CraftData* live) {
	XvtSnapshot_CopyFields((void*)record, (void*)live, g_CraftDataFields,
						   sizeof(g_CraftDataFields) / sizeof(g_CraftDataFields[0]), 0);
	for (size_t i = 0; i < sizeof(record->turretObjectLinks) / sizeof(record->turretObjectLinks[0]); ++i) {
		record->turretObjectLinks[i] =
			live->turretObjectLinks[i]
				? (uint32_t)((live->turretObjectLinks[i] - g_objectTable) * sizeof(XvtSnapshotObjectRecord) +
							 1)
				: 0;
	}
	record->effectiveAiObjectLink =
		live->effectiveAiObjectLink
			? (uint32_t)((live->effectiveAiObjectLink - g_objectTable) * sizeof(XvtSnapshotObjectRecord) + 1)
			: 0;
}

void XvtSnapshot_DecodeCraftData(CraftData* live, const XvtSnapshotCraftData* record) {
	XvtSnapshot_CopyFields((void*)record, (void*)live, g_CraftDataFields,
						   sizeof(g_CraftDataFields) / sizeof(g_CraftDataFields[0]), 1);
	for (size_t i = 0; i < sizeof(record->turretObjectLinks) / sizeof(record->turretObjectLinks[0]); ++i) {
		live->turretObjectLinks[i] =
			record->turretObjectLinks[i]
				? &g_objectTable[(record->turretObjectLinks[i] - 1) / sizeof(XvtSnapshotObjectRecord)]
				: NULL;
	}
	live->effectiveAiObjectLink =
		record->effectiveAiObjectLink
			? &g_objectTable[(record->effectiveAiObjectLink - 1) / sizeof(XvtSnapshotObjectRecord)]
			: NULL;
}

