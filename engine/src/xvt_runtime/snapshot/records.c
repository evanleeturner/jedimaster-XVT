void XvtSnapshot_EncodeObjectRecord(XvtSnapshotObjectRecord* record, const ObjectRecord* live) {
	XvtSnapshot_CopyFields((void*)record, (void*)live, g_ObjectRecordFields,
						   sizeof(g_ObjectRecordFields) / sizeof(g_ObjectRecordFields[0]), 0);
	record->mobj =
		live->mobj ? (uint32_t)((live->mobj - g_mobileObjectPoolBase) * sizeof(XvtSnapshotMobileObject) + 1)
				   : 0;
}

void XvtSnapshot_DecodeObjectRecord(ObjectRecord* live, const XvtSnapshotObjectRecord* record) {
	XvtSnapshot_CopyFields((void*)record, (void*)live, g_ObjectRecordFields,
						   sizeof(g_ObjectRecordFields) / sizeof(g_ObjectRecordFields[0]), 1);
	live->mobj =
		record->mobj ? &g_mobileObjectPoolBase[(record->mobj - 1) / sizeof(XvtSnapshotMobileObject)] : NULL;
}

