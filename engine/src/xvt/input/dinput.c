// FLAGS: /O2 /G5
// FUNCTION: XVT 0x443330
int DInput_Init(void) {
	DxGuid keyboardGuid;
	DIPROPDWORD bufferSize;
#ifdef XVT_MODERN
	AeronMessageBoxButton errorButton = { 1, "OK", 1, 1 };
	AeronMessageBoxOptions errorOptions = { AERON_MESSAGE_BOX_ERROR, "ERROR", NULL, &errorButton, 1 };
#endif

	keyboardGuid = g_directInputSystemKeyboardGuid;
	if (DirectInputCreateA(g_hInstance, 0x500, &g_directInput, NULL) != 0 &&
		DirectInputCreateA(g_hInstance, 0x300, &g_directInput, NULL) != 0) {
#ifdef XVT_MODERN
		errorOptions.message = "Direct Input Create FAILED";
		Aeron_ShowMessageBox(&errorOptions, NULL);
#else
		MessageBoxA(NULL, "Direct Input Create FAILED", "ERROR", 0);
#endif
		return 0;
	}

	if (g_directInput->lpVtbl->CreateDevice(g_directInput, &keyboardGuid, &g_dinputKeyboardDevice, NULL) !=
		0) {
#ifdef XVT_MODERN
		errorOptions.message = "Direct Input Keyboard Create FAILED";
		Aeron_ShowMessageBox(&errorOptions, NULL);
#else
		MessageBoxA(NULL, "Direct Input Keyboard Create FAILED", "ERROR", 0);
#endif
		return 0;
	}
	if (g_dinputKeyboardDevice->lpVtbl->SetDataFormat(g_dinputKeyboardDevice, &c_dfDIKeyboard) != 0) {
#ifdef XVT_MODERN
		errorOptions.message = "Direct Input Keyboard Format FAILED";
		Aeron_ShowMessageBox(&errorOptions, NULL);
#else
		MessageBoxA(NULL, "Direct Input Keyboard Format FAILED", "ERROR", 0);
#endif
		return 0;
	}
	if (g_dinputKeyboardDevice->lpVtbl->SetCooperativeLevel(g_dinputKeyboardDevice, g_flightMainWindowHandle,
															DISCL_FOREGROUND | DISCL_NONEXCLUSIVE) != 0) {
#ifdef XVT_MODERN
		errorOptions.message = "Direct Input Keyboard SCL FAILED";
		Aeron_ShowMessageBox(&errorOptions, NULL);
#else
		MessageBoxA(NULL, "Direct Input Keyboard SCL FAILED", "ERROR", 0);
#endif
		return 0;
	}

	bufferSize.diph.dwSize = sizeof(bufferSize);
	bufferSize.diph.dwHeaderSize = sizeof(bufferSize.diph);
	bufferSize.diph.dwObj = 0;
	bufferSize.diph.dwHow = 0;
	bufferSize.dwData = 32;
	if (g_dinputKeyboardDevice->lpVtbl->SetProperty(g_dinputKeyboardDevice, DINPUT_DIPROP_BUFFERSIZE,
													&bufferSize.diph) < 0) {
#ifdef XVT_MODERN
		errorOptions.message = "Direct Input Keyboard SetBufferSize FAILED";
		Aeron_ShowMessageBox(&errorOptions, NULL);
#else
		MessageBoxA(NULL, "Direct Input Keyboard SetBufferSize FAILED", "ERROR", 0);
#endif
		return 0;
	}
	if (g_dinputKeyboardDevice->lpVtbl->Acquire(g_dinputKeyboardDevice) != 0) {
#ifdef XVT_MODERN
		errorOptions.message = "Direct Input Keyboard Acquire FAILED";
		Aeron_ShowMessageBox(&errorOptions, NULL);
#else
		MessageBoxA(NULL, "Direct Input Keyboard Acquire FAILED", "ERROR", 0);
#endif
		return 0;
	}

	g_dinputKeyboardAcquired = 1;
	return 1;
}

// FUNCTION: XVT 0x4434F0
int DInput_HasKeyReady(void) {
	DIDEVICEOBJECTDATA keyEvent[2];
	uint32_t eventCount;
	HRESULT result;
	uint8_t code;
	int pressed;

	while (1) {
		do {
			eventCount = 1;
			result = g_dinputKeyboardDevice->lpVtbl->GetDeviceData(g_dinputKeyboardDevice,
																   (uint32_t)sizeof(DIDEVICEOBJECTDATA),
																   keyEvent, &eventCount, DIGDD_PEEK);
			if (result != DIERR_INPUTLOST) {
				break;
			}
			if (DInput_ReacquireKeyboard() == 0) {
				return 0;
			}
		} while (1);
		if (result < 0) {
			return 0;
		}
		if (eventCount == 0) {
			return 0;
		}

		pressed = keyEvent[0].dwData & 0x80;
		code = g_dinputKeyCodeTable[keyEvent[0].dwOfs & 0xff];
		if (code == 0xfd) {
			g_dinputShiftDown = pressed;
			eventCount = 1;
			g_dinputKeyboardDevice->lpVtbl->GetDeviceData(
				g_dinputKeyboardDevice, (uint32_t)sizeof(DIDEVICEOBJECTDATA), keyEvent, &eventCount, 0);
			continue;
		}
		if (code == 0xfe) {
			g_dinputCtrlDown = pressed;
			eventCount = 1;
			g_dinputKeyboardDevice->lpVtbl->GetDeviceData(
				g_dinputKeyboardDevice, (uint32_t)sizeof(DIDEVICEOBJECTDATA), keyEvent, &eventCount, 0);
			continue;
		}
		if (code == 0xff) {
			g_dinputAltDown = pressed;
			eventCount = 1;
			g_dinputKeyboardDevice->lpVtbl->GetDeviceData(
				g_dinputKeyboardDevice, (uint32_t)sizeof(DIDEVICEOBJECTDATA), keyEvent, &eventCount, 0);
			continue;
		}
		if (pressed != 0) {
			return 1;
		}

		eventCount = 1;
		g_dinputKeyboardDevice->lpVtbl->GetDeviceData(
			g_dinputKeyboardDevice, (uint32_t)sizeof(DIDEVICEOBJECTDATA), keyEvent, &eventCount, 0);
	}
}

// FUNCTION: XVT 0x443630
uint8_t DInput_GetKey(void) {
	DIDEVICEOBJECTDATA keyEvent[2];
	uint32_t eventCount;
	HRESULT result;
	uint32_t keyOffset;
	uint8_t code;
	int pressed;

#ifdef XVT_MODERN
	if (!g_dinputKeyboardDevice)
		return 0;
#endif
	DInput_UpdateKeyboardModifierState();
	while (1) {
		do {
			eventCount = 1;
			result = g_dinputKeyboardDevice->lpVtbl->GetDeviceData(
				g_dinputKeyboardDevice, (uint32_t)sizeof(DIDEVICEOBJECTDATA), keyEvent, &eventCount, 0);
			if (result != DIERR_INPUTLOST) {
				break;
			}
			if (DInput_ReacquireKeyboard() == 0) {
				return 0;
			}
		} while (1);
		if (result < 0) {
			return 0;
		}
		if (eventCount == 0) {
#ifdef XVT_MODERN
			return 0;
#else
			continue;
#endif
		}

		keyOffset = keyEvent[0].dwOfs;
		pressed = keyEvent[0].dwData & 0x80;
		code = g_dinputKeyCodeTable[keyOffset & 0xff];
		if (code == 0xfd) {
			g_dinputShiftDown = pressed;
			continue;
		}
		if (code == 0xfe) {
			g_dinputCtrlDown = pressed;
			continue;
		}
		if (code == 0xff) {
			g_dinputAltDown = pressed;
			continue;
		}
		if (pressed == 0) {
			continue;
		}

		if (g_dinputShiftDown != 0) {
			return g_dinputShiftKeyCodeTable[keyOffset & 0xff];
		}
		if (g_dinputCtrlDown != 0) {
			return g_dinputCtrlKeyCodeTable[keyOffset & 0xff];
		}
		if (g_dinputAltDown != 0) {
			return g_dinputAltKeyCodeTable[keyOffset & 0xff];
		}
		return g_dinputKeyCodeTable[keyOffset & 0xff];
	}
}

// FUNCTION: XVT 0x443740
void DInput_UpdateKeyboardModifierState(void) {
	uint8_t keyboardState[256];

	if (g_dinputKeyboardDevice->lpVtbl->GetDeviceState(g_dinputKeyboardDevice, sizeof(keyboardState),
													   keyboardState) == 0) {
		g_dinputShiftDown = keyboardState[42] != 0 || keyboardState[54] != 0;
		g_dinputCtrlDown = keyboardState[29] != 0 || keyboardState[157] != 0;
		g_dinputAltDown = keyboardState[56] != 0 || keyboardState[184] != 0;
	}
}

// FUNCTION: XVT 0x4437F0
HRESULT DInput_ReadKeyboardState(void) {
	uint8_t keyboardState[256];

	return g_dinputKeyboardDevice->lpVtbl->GetDeviceState(g_dinputKeyboardDevice, sizeof(keyboardState),
														  keyboardState);
}

// FUNCTION: XVT 0x443820
void DInput_Shutdown(void) {
	if (g_dinputKeyboardAcquired != 0) {
		g_dinputKeyboardDevice->lpVtbl->Unacquire(g_dinputKeyboardDevice);
		g_dinputKeyboardAcquired = 0;
	}
	if (g_dinputKeyboardDevice != 0) {
		g_dinputKeyboardDevice->lpVtbl->Release(g_dinputKeyboardDevice);
#ifdef XVT_MODERN
		g_dinputKeyboardDevice = NULL;
#endif
	}
	if (g_directInput != 0) {
		g_directInput->lpVtbl->Release(g_directInput);
#ifdef XVT_MODERN
		g_directInput = NULL;
#endif
	}
}

// FUNCTION: XVT 0x443860
int DInput_ReacquireKeyboard(void) {
#ifdef XVT_MODERN
	if (!g_dinputKeyboardDevice || !XvtInput_CanReacquireKeyboard())
		return 0;
	g_dinputKeyboardAcquired = g_dinputKeyboardDevice->lpVtbl->Acquire(g_dinputKeyboardDevice) >= 0;
	return g_dinputKeyboardAcquired;
#else
	if (g_dinputKeyboardDevice != 0) {
		g_dinputKeyboardDevice->lpVtbl->Acquire(g_dinputKeyboardDevice);
		g_dinputKeyboardAcquired = 1;
		return 1;
	}
	return 0;
#endif
}
